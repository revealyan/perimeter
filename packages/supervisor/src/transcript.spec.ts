// Ресинк из транскрипта: слаг пути, маппинг записей в элементы ленты, склейка результатов.
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { carryTranscript, projectSlug, readTranscriptItems, retargetTranscript, stripImages, transcriptPath, writeTranscript } from './transcript.js';

const dirs: string[] = [];
afterEach(() => { for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true }); });

describe('транскрипт', () => {
  it('слаг пути: не-буквенно-цифровые → дефис (правило Claude Code)', () => {
    expect(projectSlug('C:\\devs\\revealyan\\perimeter')).toBe('C--devs-revealyan-perimeter');
    expect(projectSlug('/opt/perimeter')).toBe('-opt-perimeter');
  });

  it('path складывается в projects/<слаг>/<sid>.jsonl', () => {
    expect(transcriptPath('/home/u/.claude', '/opt/x', 'sid-1')).toBe(
      join('/home/u/.claude', 'projects', '-opt-x', 'sid-1.jsonl'),
    );
  });

  it('перенос в другую среду: cwd переписывается во всех записях, мусор остаётся, writeTranscript кладёт файл под слаг нового cwd', () => {
    const cfg = mkdtempSync(join(tmpdir(), 'cc-mv-')); dirs.push(cfg);
    const src = [
      JSON.stringify({ type: 'user', cwd: '/opt/x', message: { role: 'user', content: 'привет' } }),
      JSON.stringify({ type: 'assistant', cwd: '/opt/x', message: { id: 'm' } }),
      'мусор не-json',
    ].join('\n');
    const retargeted = retargetTranscript(src, 'C:\\work\\x');
    const lines = retargeted.split('\n').filter((l) => l !== '');
    expect(lines).toHaveLength(3);
    expect(JSON.parse(lines[0]!)['cwd']).toBe('C:\\work\\x');
    expect(JSON.parse(lines[1]!)['cwd']).toBe('C:\\work\\x');
    expect(lines[2]).toBe('мусор не-json');

    const p = writeTranscript(cfg, 'C:\\work\\x', 'sid-9', retargeted);
    expect(p).toBe(join(cfg, 'projects', 'C--work-x', 'sid-9.jsonl'));
    expect(readTranscriptItems(p)!.items.map((i) => i.kind)).toEqual(['user']); // пользовательская реплика читается
  });

  it('маппинг: текст/tool_use/tool_result, результат приклеен к вызову', () => {
    const dir = mkdtempSync(join(tmpdir(), 'cc-tr-')); dirs.push(dir);
    const f = join(dir, 's.jsonl');
    writeFileSync(f, [
      JSON.stringify({ type: 'assistant', message: { id: 'm1', content: [{ type: 'text', text: 'привет' }] } }),
      JSON.stringify({ type: 'assistant', message: { id: 'm1', content: [{ type: 'tool_use', id: 't1', name: 'Bash', input: { command: 'ls' } }] } }),
      JSON.stringify({ type: 'user', message: { content: [{ type: 'tool_result', tool_use_id: 't1' }] }, toolUseResult: { stdout: 'a\nb', exitCode: 0 } }),
      JSON.stringify({ type: 'ai-title', aiTitle: 'заголовок' }), // игнорируется
      'мусор не-json', // игнорируется
    ].join('\n'), 'utf8');

    const r = readTranscriptItems(f)!;
    expect(r).not.toBeNull();
    const kinds = r.items.map((i) => i.kind);
    expect(kinds).toEqual(['text', 'tool-use']);
    const tool = r.items[1]!;
    expect(tool.data['done']).toBe(true);
    expect((tool.data['result'] as { stdout: string }).stdout).toBe('a\nb');
  });

  it('реплики пользователя строкой (так их пишет CLI) попадают в ленту; служебные user-строки — нет', () => {
    const dir = mkdtempSync(join(tmpdir(), 'cc-tr-')); dirs.push(dir);
    const f = join(dir, 's.jsonl');
    const u = (content: unknown, extra: Record<string, unknown> = {}) => JSON.stringify({ type: 'user', message: { role: 'user', content }, ...extra });
    writeFileSync(f, [
      u('почини кольцо контекста', { origin: { kind: 'human' } }),
      JSON.stringify({ type: 'assistant', message: { id: 'm1', content: [{ type: 'text', text: 'чиню' }] } }),
      u('<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>', { isMeta: true }),
      u('<command-name>/effort</command-name>\n            <command-message>effort</command-message>\n            <command-args>max</command-args>'),
      u('<local-command-stdout>Set effort level to max</local-command-stdout>'),
      u('<command-message>ui-craft</command-message>\n<command-name>/ui-craft</command-name>\n<command-args>вот макет</command-args>'),
      u('<system-reminder>\nLinked sessions now…\n</system-reminder>'),
      u('<task-notification>\n<task-id>a1</task-id>\n</task-notification>', { origin: { kind: 'task-notification' } }),
      u('This session is being continued from a previous conversation that ran out of context.', { isCompactSummary: true, isVisibleInTranscriptOnly: true }),
      u('[Image: original 2640x1760, displayed at 2000x1333.]', { isMeta: true }),
      u([{ type: 'text', text: '[Request interrupted by user]' }]),
      u([{ type: 'text', text: '<system-reminder>контекст</system-reminder>' }, { type: 'text', text: 'а вот и вопрос' }], { origin: { kind: 'human' } }),
      u('<bash-input>start .</bash-input>'),
      u('<bash-stdout>(Bash completed with no output)</bash-stdout><bash-stderr></bash-stderr>'),
      u('Another Claude session sent a message:\n<cross-session-message from="x">привет</cross-session-message>', { isMeta: true, origin: { kind: 'peer' } }),
      u('ветка субагента', { isSidechain: true }),
      u('[Image #1] смотри скрин', { origin: { kind: 'human' } }),
    ].join('\n'), 'utf8');

    const r = readTranscriptItems(f)!;
    const users = r.items.filter((i) => i.kind === 'user').map((i) => i.data['text']);
    expect(users).toEqual(['почини кольцо контекста', '/effort max', '/ui-craft вот макет', 'а вот и вопрос', '[Image #1] смотри скрин']);
    expect(r.items.map((i) => i.kind)).toEqual(['user', 'text', 'user', 'user', 'user', 'user']);
  });

  it('carryTranscript: транскрипт переезжает в каталог другого профиля (resume под новым аккаунтом)', () => {
    const dir = mkdtempSync(join(tmpdir(), 'cc-tr-')); dirs.push(dir);
    const a = join(dir, 'a'); const b = join(dir, 'b');
    const src = transcriptPath(a, '/opt/x', 'sid-1');
    mkdirSync(dirname(src), { recursive: true });
    writeFileSync(src, JSON.stringify({ type: 'user', message: { content: 'привет' } }), 'utf8');
    expect(carryTranscript(a, b, '/opt/x', 'sid-1')).toBe(true);
    expect(readTranscriptItems(transcriptPath(b, '/opt/x', 'sid-1'))!.items).toHaveLength(1);
    expect(carryTranscript(a, b, '/opt/x', 'нет-такого')).toBe(false);
  });

  it('нет файла → null', () => {
    expect(readTranscriptItems(join(tmpdir(), 'точно-нет-такого.jsonl'))).toBeNull();
  });
});

describe('картинки в результатах инструментов не гоняем в подгрузке истории', () => {
  const b64 = 'A'.repeat(4000);
  it('блок image с base64 → пометка с размером; текст рядом остаётся', () => {
    const out = stripImages([{ type: 'text', text: 'вот' }, { type: 'image', source: { type: 'base64', media_type: 'image/png', data: b64 } }]) as Array<Record<string, unknown>>;
    expect(out[0]).toEqual({ type: 'text', text: 'вот' });
    expect(out[1]).toEqual({ type: 'image', omitted: true, mediaType: 'image/png', bytes: 3000 });
  });
  it('результат Read картинки (file.base64) → file без base64, с пометкой', () => {
    const out = stripImages({ type: 'image', file: { base64: b64, type: 'image/png', originalSize: 9 } }) as { file: Record<string, unknown> };
    expect(out.file).toEqual({ type: 'image/png', originalSize: 9, omitted: true, bytes: 3000 });
  });
  it('остальное не трогается', () => {
    const v = { stdout: 'ok', nested: [{ a: 1 }], s: 'x' };
    expect(stripImages(v)).toEqual(v);
    expect(stripImages('строка')).toBe('строка');
  });
});
