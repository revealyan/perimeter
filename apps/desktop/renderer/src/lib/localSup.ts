// Статус локального supervisor'а — строка из main-процесса Electron («докачиваю движок: 2/2 · … · 45 из 153 МБ»,
// «запускается…», «запущен», «упал (код 1)…»). Пока он ставится или стартует, «запустить» и «повторить» бесполезны
// (ставится один раз на всё окно; сокет всё равно некуда открыть) — кнопки прячем, видна только строка хода.
export function localSupBusy(s: string): boolean {
  return /^(готовлю|докачиваю|запускается)/.test(s);
}
